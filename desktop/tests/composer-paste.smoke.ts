import { chmod, mkdtemp, readFile, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join, resolve } from "node:path"
import { _electron, expect, test } from "@playwright/test"
import { newChat, WorkspaceRepository } from "../src/main/workspace"

test("pasting a clipboard image attaches it in topic and chat composers without changing the draft", async ({}, testInfo) => {
  const directory = await mkdtemp(join(tmpdir(), "edu-composer-paste-"))
  const repository = new WorkspaceRepository(join(directory, "workspace"))
  await repository.load()
  const chat = newChat(repository.stateSnapshot.runners[0].id)
  const executable = resolve("tests/fixtures/provider-cli.mjs")
  await chmod(executable, 0o755)
  await repository.mutate((state) => {
    state.chats.push(chat)
    state.runners[0].provider = "claude"
    state.providerSettings.push({ id: "claude", displayName: "Fixture tutor", binaryPath: executable, enabled: true })
  })
  const { ELECTRON_RENDERER_URL: _rendererUrl, ELECTRON_RUN_AS_NODE: _nodeMode, ...environment } = process.env
  const app = await _electron.launch({ args: [resolve(".")], env: { ...environment, PRUNE_DATA_DIR: directory } })
  try {
    const png = (await readFile(resolve("src/renderer/assets/app-icon.png"))).toString("base64")
    const page = await app.firstWindow()
    await page.getByRole("button", { name: "New topic", exact: true }).click()
    const transfer = await page.evaluateHandle((base64) => {
      const blob = Uint8Array.from(atob(base64), (character) => character.charCodeAt(0))
      const transfer = new DataTransfer()
      transfer.items.add(new File([blob], "image.png", { type: "image/png" }))
      return transfer
    }, png)
    const topicInput = page.getByRole("textbox", { name: "Message your tutor" })
    await topicInput.fill("Explain this diagram")
    await topicInput.evaluate((element, clipboardData) => {
      element.dispatchEvent(new ClipboardEvent("paste", { clipboardData, bubbles: true, cancelable: true }))
    }, transfer)
    await expect(page.getByRole("button", { name: /^Remove pasted-image-/ })).toBeVisible({ timeout: 3000 })
    await expect(topicInput).toHaveText("Explain this diagram")
    expect((await page.evaluate(() => window.prune?.snapshot()))?.topics).toHaveLength(0)
    await page.getByRole("button", { name: /^Remove pasted-image-/ }).click()
    await expect(page.getByRole("button", { name: /^Remove pasted-image-/ })).toHaveCount(0)
    await app.evaluate(async ({ clipboard, ClipboardItem }, base64) => {
      const data = Uint8Array.from(atob(base64), (character) => character.charCodeAt(0))
      await clipboard.write([new ClipboardItem({ "image/png": new Blob([data], { type: "image/png" }) })])
    }, png)
    await app.evaluate(({ ipcMain }) => {
      ipcMain.removeHandler("prune:send")
      ipcMain.handle("prune:send", async () => {})
    })
    const input = page.getByRole("textbox", { name: "Message this chat" })
    await input.fill("My question")
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.paste())
    const composer = page.getByRole("form", { name: "Chat composer", exact: true })
    const preview = composer.getByRole("img", { name: /^Attached image/ })
    await expect(preview).toBeVisible()
    await expect.poll(() => preview.evaluate((image) => image instanceof HTMLImageElement && image.naturalWidth > 0)).toBe(true)
    await preview.click()
    const viewer = page.getByRole("dialog", { name: /^pasted-image-/ })
    await expect(viewer).toBeVisible()
    await expect(viewer.getByRole("img")).toBeVisible()
    await viewer.getByRole("button", { name: "Zoom in", exact: true }).click()
    await expect(viewer.getByRole("button", { name: "Reset zoom" })).toHaveText("150%")
    await viewer.getByRole("button", { name: "Close preview" }).click()
    await expect(viewer).toHaveCount(0)
    await expect(input).toHaveText("My question")
    expect((await page.evaluate(() => window.prune?.snapshot()))?.chats[0].materials).toHaveLength(0)
    await composer.getByRole("button", { name: /^Remove pasted-image-/ }).click()
    await expect(preview).toHaveCount(0)
    await input.focus()
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.paste())
    await expect(preview).toBeVisible()
    await composer.getByRole("button", { name: "Send message", exact: true }).click()
    await expect.poll(async () => (await page.evaluate(() => window.prune?.snapshot()))?.chats[0].materials.length).toBe(1)
    await expect(preview).toHaveCount(0)
    const saved = (await page.evaluate(() => window.prune?.snapshot()))?.chats[0].materials[0]
    expect(saved?.kind).toBe("image")
    const savedPath = join(repository.directory, "chats", chat.id, "assets", saved!.name)
    expect(await app.evaluate(({ nativeImage }, path) => nativeImage.createFromPath(path).getSize(), savedPath))
      .toEqual({ width: 1024, height: 1024 })
    await page.getByRole("button", { name: "New chat", exact: true }).click()
    await input.fill("New question")
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.paste())
    await expect(preview).toBeVisible()
    expect((await page.evaluate(() => window.prune?.snapshot()))?.chats).toHaveLength(1)
    await expect(input).toHaveText("New question")
    const notes = join(directory, "notes.txt")
    await writeFile(notes, "A second learning source")
    await app.evaluate(({ dialog }, path) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] })
    }, notes)
    await composer.getByRole("button", { name: "Attach files to this chat" }).click()
    await expect.poll(async () => (await page.evaluate(() => window.prune?.snapshot()))?.chats.length).toBe(2)
    await expect.poll(async () => (await page.evaluate(() => window.prune?.snapshot()))?.chats[0].materials.length).toBe(1)
    await expect(preview).toBeVisible()
    await expect(input).toHaveText("New question")
    await page.screenshot({ path: testInfo.outputPath("pasted-image-preview.png") })
    await input.fill("")
    await composer.getByRole("button", { name: "Send message", exact: true }).click()
    await expect.poll(async () => (await page.evaluate(() => window.prune?.snapshot()))?.chats.length).toBe(2)
    await expect.poll(async () => (await page.evaluate(() => window.prune?.snapshot()))?.chats[0].materials.length).toBe(2)
    await expect(preview).toHaveCount(0)
    await input.fill("")
    await input.evaluate((element) => {
      const clipboardData = new DataTransfer()
      clipboardData.setData("text/plain", "Pasted notes")
      element.dispatchEvent(new ClipboardEvent("paste", { clipboardData, bubbles: true, cancelable: true }))
    })
    await expect(input).toHaveText("Pasted notes")
  } finally {
    await app.close()
    await rm(directory, { recursive: true, force: true })
  }
})
